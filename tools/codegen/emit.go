const header = "// Code generated by tools/codegen from docs/*.xlsx and spec/harvest. DO NOT EDIT.\n\n"

func writeGo(path, src string) error {
	out, err := format.Source([]byte(src))
	if err != nil {
		_ = os.WriteFile(path+".broken", []byte(src), 0o644)
		return fmt.Errorf("gofmt %s: %w", path, err)
	}
	return os.WriteFile(path, out, 0o644)
}

func (b *builder) services() (map[string][]*Endpoint, []string) {
	m := map[string][]*Endpoint{}
	for _, e := range b.endpoints {
		m[e.ServiceType] = append(m[e.ServiceType], e)
	}
	keys := sortedKeys(m)
	return m, keys
}

func (b *builder) emit(outDir string) error {
	svcs, keys := b.services()

	// services.go
	var s strings.Builder
	s.WriteString(header + "package sonarqube\n\n")
	s.WriteString("type service struct{ client *Client }\n\n")
	s.WriteString("// services holds one field per API service.\ntype services struct {\n")
	for _, k := range keys {
		fmt.Fprintf(&s, "\t// %s wraps the %s endpoints.\n\t%s *%s\n", svcs[k][0].ServiceField, serviceArea(svcs[k]), svcs[k][0].ServiceField, k)
	}
	s.WriteString("}\n\nfunc (c *Client) initServices() {\n\tbase := service{client: c}\n")
	for _, k := range keys {
		fmt.Fprintf(&s, "\tc.%s = &%s{base}\n", svcs[k][0].ServiceField, k)
	}
	s.WriteString("}\n\n")
	for _, k := range keys {
		fmt.Fprintf(&s, "// %s wraps the %s endpoints.\ntype %s struct{ service }\n\n", k, serviceArea(svcs[k]), k)
	}
	if err := writeGo(filepath.Join(outDir, "services_gen.go"), s.String()); err != nil {
		return err
	}

	// One file per service.
	for _, k := range keys {
		var f strings.Builder
		f.WriteString(header + "package sonarqube\n\nimport (\n\t\"context\"\n\t\"encoding/json\"\n)\n\nvar _ json.RawMessage\n\n")
		for _, e := range svcs[k] {
			b.emitOptions(&f, e)
			b.emitMethod(&f, e)
		}
		name := "api_" + strings.ToLower(strings.ReplaceAll(goSnake(svcs[k][0].ServiceField), "__", "_")) + "_gen.go"
		if err := writeGo(filepath.Join(outDir, name), f.String()); err != nil {
			return err
		}
	}

	// Models.
	var m strings.Builder
	m.WriteString(header + "package sonarqube\n\nimport \"encoding/json\"\n\nvar _ json.RawMessage\n\n")
	for _, st := range b.types.sorted() {
		if st.Doc != "" {
			m.WriteString(wrapComment(st.Name+" — "+st.Doc, ""))
		} else {
			fmt.Fprintf(&m, "// %s is a generated model type.\n", st.Name)
		}
		fmt.Fprintf(&m, "type %s struct {\n", st.Name)
		for _, fd := range st.Fields {
			m.WriteString(wrapComment(fd.Doc, "\t"))
			tag := fd.JSON
			if fd.Omit {
				tag += ",omitempty"
			}
			fmt.Fprintf(&m, "\t%s %s `json:%q`\n", fd.Name, fd.Type, tag)
		}
		m.WriteString("}\n\n")
	}
	if err := writeGo(filepath.Join(outDir, "models_gen.go"), m.String()); err != nil {
		return err
	}

	if err := b.emitRegistry(outDir); err != nil {
		return err
	}
	return b.emitTests(outDir)
}

func goSnake(s string) string {
	return strings.Join(splitWords(s), "_")
}

func serviceArea(es []*Endpoint) string {
	p := es[0].Path
	parts := strings.Split(strings.TrimPrefix(p, "/"), "/")
	if len(parts) >= 3 && parts[1] == "v2" {
		return "api/v2/" + parts[2]
	}
	if len(parts) >= 2 {
		return parts[0] + "/" + parts[1]
	}
	return p
}

func (b *builder) hasOptions(e *Endpoint) bool { return len(e.Params) > 0 || e.BodyType != "" }

func (b *builder) emitOptions(f *strings.Builder, e *Endpoint) {
	if !b.hasOptions(e) {
		return
	}
	fmt.Fprintf(f, "// %s holds the parameters of [%s.%s].\ntype %s struct {\n", e.OptionsType(), e.ServiceType, e.Method, e.OptionsType())
	for _, p := range e.Params {
		f.WriteString(wrapComment(p.Doc, "\t"))
		var tag string
		switch p.In {
		case "path":
			tag = fmt.Sprintf(`path:"%s"`, p.Name)
		case "file":
			tag = fmt.Sprintf(`file:"%s"`, p.Name)
		case "header":
			tag = fmt.Sprintf(`header:"%s"`, p.Name)
		default:
			n := p.Name
			if p.Comma {
				n += ",comma"
			}
			tag = fmt.Sprintf(`url:"%s"`, n)
		}
		fmt.Fprintf(f, "\t%s %s `%s`\n", p.Field, p.GoType, tag)
	}
	if e.BodyType != "" {
		f.WriteString("\t// Body is the request body.\n")
		fmt.Fprintf(f, "\tBody %s `body:\"\"`\n", e.BodyType)
	}
	f.WriteString("}\n\n")
}

func (e *Endpoint) returns() (string, string) {
	switch e.RespKind {
	case "json":
		return "*" + e.RespType, "nil"
	case "jsonval":
		switch e.RespType {
		case "string":
			return e.RespType, `""`
		case "int", "int64", "float64":
			return e.RespType, "0"
		case "bool":
			return e.RespType, "false"
		}
		return e.RespType, "nil"
	case "bytes":
		return "[]byte", "nil"
	case "rawjson", "rawjsonopt":
		return "json.RawMessage", "nil"
	}
	return "", ""
}

func (e *Endpoint) methodDoc() string {
	var parts []string
	doc := e.Doc
	if doc == "" {
		doc = "calls " + e.HTTPMethod + " " + e.Path + "."
	}
	parts = append(parts, e.Method+" "+lowerFirst(doc))
	parts = append(parts, "")
	parts = append(parts, "API: "+e.HTTPMethod+" "+e.Path)
	var notes []string
	if e.Since != "" {
		notes = append(notes, "Since "+e.Since+".")
	}
	if e.Internal {
		notes = append(notes, "Internal: SonarQube may change this endpoint without notice.")
	}
	if n := availabilityNote(sheetColumns, e.Avail, func(s string) bool { return s == "Y" || s == "I" }); n != "" {
		notes = append(notes, n)
	}
	if len(notes) > 0 {
		parts = append(parts, "", strings.Join(notes, " "))
	}
	if e.Deprecated != "" {
		dep := "Deprecated: SonarQube deprecated this endpoint"
		if e.Deprecated != "unknown" {
			dep += " in " + e.Deprecated
		}
		parts = append(parts, "", dep+".")
	}
	return wrapComment(strings.Join(parts, "\n"), "")
}

var sheetColumns []string

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	// Keep acronyms and identifiers intact.
	if len(s) > 1 && s[1] >= 'A' && s[1] <= 'Z' {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

func (b *builder) emitMethod(f *strings.Builder, e *Endpoint) {
	ret, zero := e.returns()
	args := "ctx context.Context"
	optArg := "nil"
	if b.hasOptions(e) {
		args += ", opts *" + e.OptionsType()
		optArg = "opts"
	}
	kind := "apiV1"
	if e.API == "v2" {
		kind = "apiV2"
	}
	ep := fmt.Sprintf("endpoint{method: %q, path: %q, kind: %s", e.HTTPMethod, e.Path, kind)
	if e.Accept != "" {
		ep += fmt.Sprintf(", accept: %q", e.Accept)
	}
	if e.BodyContentType != "" {
		ep += fmt.Sprintf(", contentType: %q", e.BodyContentType)
	}
	if e.Multipart {
		ep += ", multipart: true"
	}
	ep += "}"
	f.WriteString(e.methodDoc())
	switch e.RespKind {
	case "json":
		fmt.Fprintf(f, "func (s *%s) %s(%s) (%s, *Response, error) {\n", e.ServiceType, e.Method, args, ret)
		fmt.Fprintf(f, "\tout := new(%s)\n", e.RespType)
		fmt.Fprintf(f, "\tresp, err := s.client.call(ctx, %s, %s, out)\n", ep, optArg)
		fmt.Fprintf(f, "\tif err != nil {\n\t\treturn %s, resp, err\n\t}\n\treturn out, resp, nil\n}\n\n", zero)
	case "jsonval":
		fmt.Fprintf(f, "func (s *%s) %s(%s) (%s, *Response, error) {\n", e.ServiceType, e.Method, args, ret)
		fmt.Fprintf(f, "\tvar out %s\n", e.RespType)
		fmt.Fprintf(f, "\tresp, err := s.client.call(ctx, %s, %s, &out)\n", ep, optArg)
		fmt.Fprintf(f, "\tif err != nil {\n\t\treturn %s, resp, err\n\t}\n\treturn out, resp, nil\n}\n\n", zero)
	case "bytes":
		fmt.Fprintf(f, "func (s *%s) %s(%s) ([]byte, *Response, error) {\n", e.ServiceType, e.Method, args)
		f.WriteString("\tvar out []byte\n")
		fmt.Fprintf(f, "\tresp, err := s.client.call(ctx, %s, %s, &out)\n", ep, optArg)
		f.WriteString("\tif err != nil {\n\t\treturn nil, resp, err\n\t}\n\treturn out, resp, nil\n}\n\n")
	case "rawjson", "rawjsonopt":
		fmt.Fprintf(f, "func (s *%s) %s(%s) (json.RawMessage, *Response, error) {\n", e.ServiceType, e.Method, args)
		f.WriteString("\tvar out []byte\n")
		fmt.Fprintf(f, "\tresp, err := s.client.call(ctx, %s, %s, &out)\n", ep, optArg)
		f.WriteString("\tif err != nil {\n\t\treturn nil, resp, err\n\t}\n\treturn json.RawMessage(out), resp, nil\n}\n\n")
	default:
		fmt.Fprintf(f, "func (s *%s) %s(%s) (*Response, error) {\n", e.ServiceType, e.Method, args)
		fmt.Fprintf(f, "\treturn s.client.call(ctx, %s, %s, nil)\n}\n\n", ep, optArg)
	}
}

func (b *builder) emitRegistry(outDir string) error {
	var s strings.Builder
	s.WriteString(header + "package sonarqube\n\n")
	s.WriteString("var versionColumns = []string{")
	for _, c := range sheetColumns {
		fmt.Fprintf(&s, "%q, ", c)
	}
	s.WriteString("}\n\nvar endpointRegistry = []EndpointInfo{\n")
	for _, e := range b.endpoints {
		avail := make([]byte, len(e.Avail))
		for i, a := range e.Avail {
			switch a {
			case "Y", "I", "M":
				avail[i] = a[0]
			default:
				avail[i] = '-'
			}
		}
		fmt.Fprintf(&s, "\t{Service: %q, Method: %q, HTTPMethod: %q, Path: %q, API: %q, Internal: %t, Deprecated: %t, ContentType: %q, Multipart: %t, availability: %q, Params: []ParamInfo{",
			e.ServiceField, e.Method, e.HTTPMethod, e.Path, e.API, e.Internal, e.Deprecated != "", e.BodyContentType, e.Multipart, string(avail))
		for _, p := range e.Params {
			fmt.Fprintf(&s, "{Name: %q, In: %q, Required: %t, Multi: %t}, ", p.Name, p.In, p.Required, strings.HasPrefix(p.GoType, "[]"))
		}
		if e.BodyType != "" {
			s.WriteString(`{Name: "body", In: "body"}, `)
		}
		s.WriteString("}},\n")
	}
	s.WriteString("}\n")
	return writeGo(filepath.Join(outDir, "registry_gen.go"), s.String())
}

// sample returns Go source for a sample value of type t and its expected
// wire encoding.
func sample(p *Param) (src string, wire []string) {
	switch p.GoType {
	case "string":
		v := "v-" + p.Name
		return strconv.Quote(v), []string{v}
	case "*string":
		v := "v-" + p.Name
		return "Ptr(" + strconv.Quote(v) + ")", []string{v}
	case "*int":
		return "Ptr(7)", []string{"7"}
	case "*int64":
		return "Ptr[int64](7)", []string{"7"}
	case "*float64":
		return "Ptr(1.5)", []string{"1.5"}
	case "*bool":
		return "Ptr(true)", []string{"true"}
	case "[]string":
		if p.Comma {
			return `[]string{"a", "b"}`, []string{"a,b"}
		}
		return `[]string{"a", "b"}`, []string{"a", "b"}
	case "[]int":
		return `[]int{1, 2}`, []string{"1", "2"}
	case "*File":
		return `&File{Name: "f.txt", Content: strings.NewReader("data")}`, []string{"data"}
	}
	return "", nil
}

func (b *builder) emitTests(outDir string) error {
	var s strings.Builder
	s.WriteString(header + "package sonarqube\n\nimport (\n\t\"context\"\n\t\"strings\"\n)\n\nvar _ = strings.NewReader\n\n")
	s.WriteString("var generatedCases = []generatedCase{\n")
	for _, e := range b.endpoints {
		path := e.Path
		var fields []string
		var params []string
		var files []string
		for _, p := range e.Params {
			src, wire := sample(p)
			if src == "" {
				continue
			}
			if p.In == "path" {
				src = strconv.Quote("pv-" + p.Name)
				path = strings.ReplaceAll(path, "{"+p.Name+"}", "pv-"+p.Name)
				fields = append(fields, fmt.Sprintf("%s: %s", p.Field, src))
				continue
			}
			fields = append(fields, fmt.Sprintf("%s: %s", p.Field, src))
			switch p.In {
			case "file":
				files = append(files, p.Name)
			case "header":
				params = append(params, fmt.Sprintf("%q: {%q}", "header:"+p.Name, wire[0]))
			default:
				var qs []string
				for _, w := range wire {
					qs = append(qs, strconv.Quote(w))
				}
				params = append(params, fmt.Sprintf("%q: {%s}", p.Name, strings.Join(qs, ", ")))
			}
		}
		hasBody := false
		if e.BodyType != "" {
			hasBody = true
			switch {
			case strings.HasPrefix(e.BodyType, "*"):
				fields = append(fields, "Body: &"+e.BodyType[1:]+"{}")
			case e.BodyType == "string":
				fields = append(fields, `Body: "body"`)
			case strings.HasPrefix(e.BodyType, "[]*"):
				fields = append(fields, "Body: "+e.BodyType+"{{}}")
			default:
				fields = append(fields, "Body: "+e.BodyType+"{}")
			}
		}
		call := fmt.Sprintf("c.%s.%s(ctx", e.ServiceField, e.Method)
		if b.hasOptions(e) {
			call += fmt.Sprintf(", &%s{%s}", e.OptionsType(), strings.Join(fields, ", "))
		}
		call += ")"
		var fn, resp string
		switch e.RespKind {
		case "none":
			fn = fmt.Sprintf("func(ctx context.Context, c *Client) (any, *Response, error) { r, err := %s; return nil, r, err }", call)
		default:
			fn = fmt.Sprintf("func(ctx context.Context, c *Client) (any, *Response, error) { return %s }", call)
		}
		switch e.RespKind {
		case "json":
			resp = e.Example
			if resp == "" {
				resp = "{}"
			}
		case "jsonval":
			switch {
			case strings.HasPrefix(e.RespType, "[]"):
				resp = "[]"
			case e.RespType == "string":
				resp = `"s"`
			default:
				resp = "{}"
			}
			if e.Example != "" {
				resp = e.Example
			}
		case "rawjson", "rawjsonopt":
			resp = `{"k":"v"}`
		case "bytes":
			resp = "data"
		}
		fmt.Fprintf(&s, "\t{\n\t\tname: %q, method: %q, path: %q, kind: %q, body: %t,\n", e.ServiceField+"."+e.Method, e.HTTPMethod, path, e.RespKind, hasBody)
		sort.Strings(params)
		fmt.Fprintf(&s, "\t\tparams: map[string][]string{%s},\n", strings.Join(params, ", "))
		if len(files) > 0 {
			fmt.Fprintf(&s, "\t\tfiles: %#v,\n", files)
		}
		fmt.Fprintf(&s, "\t\tresponse: %s,\n", goRawString(resp))
		fmt.Fprintf(&s, "\t\tcall: %s,\n\t},\n", fn)
	}
	s.WriteString("}\n")
	return writeGo(filepath.Join(outDir, "api_cases_gen_test.go"), s.String())
}

func goRawString(s string) string {
	if !strings.Contains(s, "`") {
		return "`" + s + "`"
	}
	return strconv.Quote(s)
}
